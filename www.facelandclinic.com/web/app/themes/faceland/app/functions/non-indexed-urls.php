/**
 * Excludes posts from XML sitemaps.
 *
 * @return array The IDs of posts to exclude.
 */
function faceland_exclude_posts_from_xml_sitemaps() {

	global $wpdb;

	// Permalink values
	$permalinks = exclude_sitemap_url();

	// Generate the LIKE pattern for each permalink value
	$like_patterns = array();
	foreach ($permalinks as $permalink) {
	    $like_patterns[] = '%' . $wpdb->esc_like($permalink) . '%';
	}

	// Prepare the LIKE conditions
	$like_conditions = implode(' OR ', array_fill(0, count($like_patterns), 'permalink LIKE %s'));

	// SQL query with LIKE operator
	$query = $wpdb->prepare("
	    SELECT object_id
	    FROM {$wpdb->prefix}yoast_indexable
	    WHERE $like_conditions
	", $like_patterns);

	// Execute the query
	$results = $wpdb->get_results($query, ARRAY_A);

	if ($results) {
	    // Extract object_id values into an array
	    $objectIds = wp_list_pluck($results, 'object_id');

	    return $objectIds;
	} else {
	    echo "No results found.";
	}
}

add_filter( 'wpseo_exclude_from_sitemap_by_post_ids', 'faceland_exclude_posts_from_xml_sitemaps' );

